// Country names from ISO 3166 (pycountry 26.2.16), with common names where helpful.
// Calling codes from Google libphonenumber (phonenumbers 9.0.44, Apache-2.0).
class CallingCountry {
  const CallingCountry(this.iso, this.name, this.dial);

  final String iso;
  final String name;
  final String dial;

  String internationalize(String national) {
    if (national.startsWith('+')) return national;
    final lengths = _zeroTrunkLengths[iso];
    if (national.startsWith('0') &&
        lengths != null &&
        !lengths.contains(national.length) &&
        lengths.contains(national.length - 1)) {
      national = national.substring(1);
    }
    return '$dial$national';
  }

  String get label => '$name ($dial)';
}

